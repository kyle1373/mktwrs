import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
import Module from 'node:module';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {routeData} from '../lib/data.mjs';
const require=createRequire(import.meta.url);
const swc=require('next/dist/build/swc');
await swc.loadBindings();
const page=fs.readFileSync(new URL('../app/archive.jsx',import.meta.url),'utf8');
const selected=page.slice(page.indexOf('function EvidenceTimes('),page.indexOf('function SplitSourceNote('))+page.slice(page.indexOf('function HalloweenRecording('),page.indexOf('function HalloweenSupportingResults('));
const {code}=await swc.transform('function Player({id}){return <span>{id}</span>;}\n'+selected+'\nexports.HalloweenRecording=HalloweenRecording;', {filename:'result-report-times.jsx',jsc:{parser:{syntax:'ecmascript',jsx:true},transform:{react:{runtime:'automatic'}}},module:{type:'commonjs'}});
const filename=new URL('../app/result-report-times-render.cjs',import.meta.url).pathname;
const compiled=new Module(filename);
compiled.paths=Module._nodeModulePaths(new URL('../app',import.meta.url).pathname);
compiled._compile(code,filename);
const render=r=>renderToStaticMarkup(React.createElement(compiled.exports.HalloweenRecording,{comparison:r,players:[]}));
test('actual NBC comparison renders faster pending video and separate share/publication clocks',()=>{
 const c=routeData(['course','3ds-neo-bowser-city']).data.halloween2019Recording;
 const html=render(c);
 assert.match(html,/Faster video references awaiting verification/);
 assert.match(html,/1:28.48/);
 assert.match(html,/jeZCQCMQgPE/);
 assert.match(html,/2019-10-23 14:13:24 UTC/);
 assert.match(html,/2019-10-23 15:02:49 UTC/);
 assert.match(html,/reported times do not replace the reviewed recording/);
 assert.match(html,/Fastest full-race recording in the reviewed evidence/);
});
